const fs = require('node:fs');
const path = require('node:path');
const { sanitize } = require('../src');

const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'web', 'index.html');
const bundlePath = path.join(root, 'web', 'mako-edifact-sanitizer.browser.js');
const html = fs.readFileSync(htmlPath, 'utf8');
const bundle = fs.readFileSync(bundlePath, 'utf8');

const blockedHtmlPatterns = [
  /<script[^>]+src=["']https?:\/\//i,
  /fetch\s*\(/i,
  /XMLHttpRequest/i,
  /sendBeacon/i,
  /WebSocket/i,
  /<script[^>]+(defer\s+)?data-domain=/i,
];
for (const pattern of blockedHtmlPatterns) {
  if (pattern.test(html)) throw new Error(`web ui contains blocked network/external pattern: ${pattern}`);
}
if (!html.includes('mako-edifact-sanitizer.browser.js')) {
  throw new Error('web ui does not load the generated sanitizer browser bundle');
}
if (/function\s+sanitizeText\s*\(/.test(html)) {
  throw new Error('web ui still contains standalone sanitizeText implementation');
}
if (!/Generated by scripts\/build-web-bundle\.js from src\/index\.js/.test(bundle)) {
  throw new Error('browser bundle is not marked as generated from src/index.js');
}
if (!/MakoEdifactSanitizer\.sanitize\(text\)/.test(html)) {
  throw new Error('web ui controller does not call MakoEdifactSanitizer.sanitize(text)');
}
if (!/output['"]\)\.textContent\s*=\s*result\.sanitizedEdifact/.test(html)) {
  throw new Error('web ui controller does not render sanitizedEdifact output');
}
if (!/report['"]\)\.textContent\s*=\s*JSON\.stringify\(result\.report,\s*null,\s*2\)/.test(html)) {
  throw new Error('web ui controller does not render the library report JSON');
}

delete globalThis.MakoEdifactSanitizer;
delete require.cache[require.resolve(bundlePath)];
require(bundlePath);
const browser = globalThis.MakoEdifactSanitizer;
if (!browser || typeof browser.sanitize !== 'function') {
  throw new Error('browser bundle did not expose MakoEdifactSanitizer.sanitize');
}

for (const fixtureName of [
  'mscons.synthetic.edi',
  'utilmd.synthetic.edi',
  'aperak.synthetic.edi',
  'invoic.nad-address-regression.synthetic.edi',
]) {
  const fixture = fs.readFileSync(path.join(root, 'fixtures', fixtureName), 'utf8');
  const webResult = browser.sanitize(fixture);
  const libraryResult = sanitize(fixture);
  if (webResult.sanitizedEdifact !== libraryResult.sanitizedEdifact) {
    throw new Error(`browser bundle output differs from library output for ${fixtureName}`);
  }
  if (JSON.stringify(webResult.report) !== JSON.stringify(libraryResult.report)) {
    throw new Error(`browser bundle report differs from library report for ${fixtureName}`);
  }
}

const invoic = fs.readFileSync(
  path.join(root, 'fixtures', 'invoic.nad-address-regression.synthetic.edi'),
  'utf8'
);
const invoicResult = browser.sanitize(invoic);
const reportJson = JSON.stringify(invoicResult.report);
const leakTargets = [
  'max.mustermann@example.test',
  'DE0012345678901234567890123456789',
  'Regionalwerke Beispiel GmbH',
  'Lieferant Beispiel GmbH & Co. KG',
  'Hauptstr.',
  'Parsevalstr.',
  'Musterstadt',
  '37170',
];
for (const raw of leakTargets) {
  if (invoicResult.sanitizedEdifact.includes(raw) || reportJson.includes(raw)) {
    throw new Error(`browser bundle leaked raw fixture value: ${raw}`);
  }
}

console.log('static web ui smoke ok: generated bundle matches library output and no EDIFACT network submission patterns');
