const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { sanitize } = require('../src');

const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'web', 'index.html');
const bundlePath = path.join(root, 'web', 'mako-edifact-sanitizer.browser.js');
const html = fs.readFileSync(htmlPath, 'utf8');
const bundle = fs.readFileSync(bundlePath, 'utf8');

const blockedHtmlPatterns = [
  /<script[^>]+src=["']https?:\/\//i,
  /fetch\s*\(/i,
  /XMLHttpRequest/i,
  /sendBeacon/i,
  /WebSocket/i,
  /<script[^>]+(defer\s+)?data-domain=/i,
];
for (const pattern of blockedHtmlPatterns) {
  if (pattern.test(html)) throw new Error(`web ui contains blocked network/external pattern: ${pattern}`);
}
if (!html.includes('mako-edifact-sanitizer.browser.js')) {
  throw new Error('web ui does not load the generated sanitizer browser bundle');
}
if (/function\s+sanitizeText\s*\(/.test(html)) {
  throw new Error('web ui still contains standalone sanitizeText implementation');
}
if (!/Generated by scripts\/build-web-bundle\.js from src\/index\.js/.test(bundle)) {
  throw new Error('browser bundle is not marked as generated from src/index.js');
}

class Element {
  constructor(id) {
    this.id = id;
    this.value = '';
    this.textContent = '';
    this.checked = false;
    this.listeners = {};
  }

  addEventListener(name, fn) {
    this.listeners[name] = fn;
  }

  click() {
    if (this.listeners.click) this.listeners.click();
  }

  change() {
    if (this.listeners.change) this.listeners.change();
  }
}

const elements = {};
for (const id of [
  'input',
  'output',
  'report',
  'sample',
  'sanitize',
  'confirm-example',
  'copy-output',
  'copy-report',
  'download-output',
  'download-report',
]) {
  elements[id] = new Element(id);
}

const document = {
  getElementById(id) {
    if (!elements[id]) elements[id] = new Element(id);
    return elements[id];
  },
  createElement() {
    return { click() {} };
  },
};

const context = vm.createContext({
  document,
  navigator: { clipboard: { writeText() {} } },
  Blob: function Blob() {},
  URL: { createObjectURL() { return 'blob:local'; }, revokeObjectURL() {} },
});
context.window = context;
vm.runInContext(bundle, context, { filename: bundlePath });
const inlineScript = html.match(/<script>([\s\S]*)<\/script>/i);
if (!inlineScript) throw new Error('web ui inline controller script not found');
vm.runInContext(inlineScript[1], context, { filename: htmlPath });

elements['confirm-example'].checked = true;
elements['confirm-example'].change();
elements.sanitize.click();
const output = elements.output.textContent;
const report = elements.report.textContent;
const libraryResult = sanitize(elements.input.value);
if (output !== libraryResult.sanitizedEdifact) {
  throw new Error('web ui sample output differs from library sanitize() output');
}
if (report !== JSON.stringify(libraryResult.report, null, 2)) {
  throw new Error('web ui sample report differs from library sanitize() report');
}

for (const fixtureName of ['mscons.synthetic.edi', 'utilmd.synthetic.edi', 'aperak.synthetic.edi', 'invoic.nad-address-regression.synthetic.edi']) {
  const fixture = fs.readFileSync(path.join(root, 'fixtures', fixtureName), 'utf8');
  elements.input.value = fixture;
  elements.sanitize.click();
  const expected = sanitize(fixture);
  if (elements.output.textContent !== expected.sanitizedEdifact) {
    throw new Error(`web ui output differs from library output for ${fixtureName}`);
  }
  if (elements.report.textContent !== JSON.stringify(expected.report, null, 2)) {
    throw new Error(`web ui report differs from library report for ${fixtureName}`);
  }
}

const leakTargets = ['max.mustermann@example.test', 'DE0012345678901234567890123456789', 'Regionalwerke Beispiel GmbH'];
for (const raw of leakTargets) {
  if (elements.output.textContent.includes(raw) || elements.report.textContent.includes(raw)) {
    throw new Error(`web ui leaked raw fixture value: ${raw}`);
  }
}

console.log('static web ui smoke ok: generated bundle matches library output and no EDIFACT network submission patterns');
